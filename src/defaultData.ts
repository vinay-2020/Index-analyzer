export function getProcessedInitialData(): IndexDataRow[] {
  return SAMPLE_FYERS_INDICES.map((item, idx) => {
    const aboveEma200 = item.ema200 ? item.close > item.ema200 : false;
    const rsi = item.rsi14 ?? 50;
    const healthyPullback = aboveEma200 && rsi >= 45 && rsi <= 60;
    const historical = getHistoricalMetricsForSymbol(item.symbol, item.name);

    return {
      ...item,
      id: `index-${idx + 1}`,
      aboveEma200,
      healthyPullback,
      historical,
    };
  });
}

// Convert indices data back to standard CSV string (for Gemini API payload and export)
export function indicesToCsv(data: IndexDataRow[]): string {
  const headers = [
    'SYMBOL',
    'NAME',
    'CATEGORY',
    'DATE',
    'OPEN',
    'HIGH',
    'LOW',
    'CLOSE',
    'PREV_CLOSE',
    'CHANGE_PCT',
    'EMA_20',
    'EMA_50',
    'EMA_200',
    'RSI_14',
    'MACD',
    'MACD_SIGNAL',
    'MACD_HIST',
    'MACD_CROSS',
    'ABOVE_200_EMA',
    'HEALTHY_PULLBACK',
    'CAGR_1Y',
    'CAGR_3Y',
    'CAGR_5Y',
    'CAGR_10Y',
    'CAGR_15Y',
    'CAGR_MAX',
    'TOTAL_RETURN_PCT',
    'ANNUAL_VOLATILITY',
    'MAX_DRAWDOWN_PCT',
    'POSITIVE_YEAR_PCT',
    'GROWTH_OF_100K',
  ];

  const rows = data.map((d) => [
    d.symbol,
    `"${d.name}"`,
    d.category,
    d.date,
    d.open,
    d.high,
    d.low,
    d.close,
    d.prevClose,
    d.changePercent.toFixed(2),
    d.ema20 ?? '',
    d.ema50 ?? '',
    d.ema200 ?? '',
    d.rsi14 ?? '',
    d.macd ?? '',
    d.macdSignal ?? '',
    d.macdHist ?? '',
    d.macdCross,
    d.aboveEma200 ? 'TRUE' : 'FALSE',
    d.healthyPullback ? 'TRUE' : 'FALSE',
    d.historical?.cagr1Y ?? '',
    d.historical?.cagr3Y ?? '',
    d.historical?.cagr5Y ?? '',
    d.historical?.cagr10Y ?? '',
    d.historical?.cagr15Y ?? '',
    d.historical?.cagrMax ?? '',
    d.historical?.totalReturnPct ?? '',
    d.historical?.annualizedVolatility ?? '',
    d.historical?.maxDrawdownPct ?? '',
    d.historical?.positiveYearPct ?? '',
    d.historical?.growthOf100k ?? '',
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
