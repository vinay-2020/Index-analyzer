// Engine 1: Index vs Benchmark Analysis
// ===========================================================================
export function computeBenchmarkComparison(
  targetKey: string,
  period: IntelligencePeriod = '15Y'
): BenchmarkComparisonStats {
  const targetMeta = HMIE_INDEX_UNIVERSE.find((u) => u.key === targetKey) || HMIE_INDEX_UNIVERSE[0];
  const targetAllCandles = getDailyCandlesForIndex(targetKey);
  const { candles: targetCandles, isSufficient, years } = sliceCandlesByPeriod(targetAllCandles, period);

  const startDate = targetCandles[0]?.date || '2011-01-03';
  const endDate = targetCandles[targetCandles.length - 1]?.date || '2026-09-18';

  const computeStats = (candles: DailyCandle[], sym: string, name: string) => {
    if (!candles || candles.length < 2) {
      return { symbol: sym, name, cumulativeReturnPct: 0, cagr: 0, annualizedVolatility: 0, maxDrawdownPct: 0, positiveYearPct: 0 };
    }
    const startClose = candles[0].close;
    const endClose = candles[candles.length - 1].close;
    const cumRet = Number((((endClose - startClose) / startClose) * 100).toFixed(2));
    const cagr = Number(((Math.pow(endClose / startClose, 1 / Math.max(1, years)) - 1) * 100).toFixed(2));

    // Volatility
    let sumSq = 0;
    const dailyReturns = candles.slice(1).map((c, idx) => (c.close - candles[idx].close) / candles[idx].close);
    const meanDaily = dailyReturns.reduce((a, b) => a + b, 0) / dailyReturns.length;
    for (const r of dailyReturns) {
      sumSq += Math.pow(r - meanDaily, 2);
    }
    const dailyStd = Math.sqrt(sumSq / Math.max(1, dailyReturns.length - 1));
    const annualizedVol = Number((dailyStd * Math.sqrt(252) * 100).toFixed(1));

    // Max Drawdown
    let peak = candles[0].close;
    let maxDd = 0;
    for (const c of candles) {
      if (c.close > peak) peak = c.close;
      const dd = ((c.close - peak) / peak) * 100;
      if (dd < maxDd) maxDd = dd;
    }

    // Positive Calendar Years (Completed calendar years only: 2011 through 2025; 2026 is incomplete YTD)
    const yearlyFirstLast = new Map<number, { first: number; last: number }>();
    for (const c of candles) {
      const yr = parseInt(c.date.slice(0, 4));
      if (yr >= 2026) continue; // Exclude incomplete 2026 calendar year (data through 2026-09-18)
      if (!yearlyFirstLast.has(yr)) {
        yearlyFirstLast.set(yr, { first: c.close, last: c.close });
      } else {
        yearlyFirstLast.get(yr)!.last = c.close;
      }
    }
    let posYears = 0;
    yearlyFirstLast.forEach(({ first, last }) => {
      if (last > first) posYears++;
    });
    const positiveYearPct = Number(((posYears / Math.max(1, yearlyFirstLast.size)) * 100).toFixed(1));

    return {
      symbol: sym,
      name,
      cumulativeReturnPct: cumRet,
      cagr,
      annualizedVolatility: annualizedVol,
      maxDrawdownPct: Number(maxDd.toFixed(1)),
      positiveYearPct,
    };
  };

  const targetStats = computeStats(targetCandles, targetMeta.symbol, targetMeta.name);

  // NIFTY 50 Baseline
  const nifty50AllCandles = getDailyCandlesForIndex('NIFTY50');
  const nifty50Candles = nifty50AllCandles.filter((c) => c.date >= startDate && c.date <= endDate);
  const nifty50Stats = computeStats(nifty50Candles, 'NSE:NIFTY50-INDEX', 'NIFTY 50');
  const nifty50Relative = Number((targetStats.cumulativeReturnPct - nifty50Stats.cumulativeReturnPct).toFixed(2));
  const nifty50Outperf = Math.round((targetStats.cagr - nifty50Stats.cagr) * 100);

  // Parent Benchmark
  let parentStats: BenchmarkComparisonStats['parentBenchmark'] = null;
  if (targetMeta.parentBenchmarkKey) {
    const parentMeta = HMIE_INDEX_UNIVERSE.find((u) => u.key === targetMeta.parentBenchmarkKey);
    if (parentMeta) {
      const parentAll = getDailyCandlesForIndex(parentMeta.key);
      const parentSliced = parentAll.filter((c) => c.date >= startDate && c.date <= endDate);
      const baseParent = computeStats(parentSliced, parentMeta.symbol, parentMeta.name);
      parentStats = {
        ...baseParent,
        available: true,
        relativeReturnPct: Number((targetStats.cumulativeReturnPct - baseParent.cumulativeReturnPct).toFixed(2)),
        outperformanceBps: Math.round((targetStats.cagr - baseParent.cagr) * 100),
      };
    }
  }

  return {
    period,
    isHistorySufficient: isSufficient,
    yearsCovered: years,
    startDate,
    endDate,
    target: targetStats,
    parentBenchmark: parentStats,
    nifty50Baseline: {
      ...nifty50Stats,
      relativeReturnPct: nifty50Relative,
      outperformanceBps: nifty50Outperf,
    },
  };
}

// ===========================================================================
// Engine 2: Correction & Recovery Analysis
// ===========================================================================
export function computeCorrectionRecoveryAnalysis(
  indexKey: string,
  period: IntelligencePeriod = 'MAX'
): {
  episodes: HistoricalCorrectionEpisode[];
  bucketSummaries: CorrectionBucketSummary[];
  deepDrawdowns: DeepDrawdownEpisode[];
} {
  const allCandles = getDailyCandlesForIndex(indexKey);
  const { candles } = sliceCandlesByPeriod(allCandles, period);

  if (candles.length < 150) {
    return { episodes: [], bucketSummaries: [], deepDrawdowns: [] };
  }

  // --- A. Short-Term Rebound by Correction Depth (Trough -> Highest Close within 120 sessions) ---
  const episodes: HistoricalCorrectionEpisode[] = [];
  let peakClose = candles[0].close;
  let peakDate = candles[0].date;
  let peakIdx = 0;

  let inDrawdown = false;
  let troughClose = candles[0].close;
  let troughDate = candles[0].date;
  let troughIdx = 0;

  for (let i = 1; i < candles.length; i++) {
    const currentClose = candles[i].close;

    if (currentClose > peakClose && !inDrawdown) {
      peakClose = currentClose;
      peakDate = candles[i].date;
      peakIdx = i;
      troughClose = currentClose;
      troughDate = candles[i].date;
      troughIdx = i;
    } else {
      const dd = ((currentClose - peakClose) / peakClose) * 100;
      if (dd <= -5.0) {
        // Entered correction territory
        if (!inDrawdown) {
          inDrawdown = true;
          troughClose = currentClose;
          troughDate = candles[i].date;
          troughIdx = i;
          // Scan from peakIdx + 1 to i to establish the lowest price reached
          for (let k = peakIdx + 1; k <= i; k++) {
            if (candles[k].close < troughClose) {
              troughClose = candles[k].close;
              troughDate = candles[k].date;
              troughIdx = k;
            }
          }
        } else {
          if (currentClose < troughClose) {
            troughClose = currentClose;
            troughDate = candles[i].date;
            troughIdx = i;
          }
        }
      }

      // Check if price recovered to a new high or completed the trough cycle
      if (inDrawdown && (currentClose >= peakClose * 0.98 || i === candles.length - 1 || (currentClose > troughClose * 1.15 && i - troughIdx > 40))) {
        // Record completed correction episode
        const depthPct = Number((((troughClose - peakClose) / peakClose) * 100).toFixed(2));
        
        // Scan up to 120 trading sessions forward from trough to find highest close
        const windowEnd = Math.min(candles.length - 1, troughIdx + 120);
        let maxRecoveryClose = troughClose;
        let maxRecoveryDate = troughDate;
        let sessionsToPeak = 0;

        for (let w = troughIdx + 1; w <= windowEnd; w++) {
          if (candles[w].close > maxRecoveryClose) {
            maxRecoveryClose = candles[w].close;
            maxRecoveryDate = candles[w].date;
            sessionsToPeak = w - troughIdx;
          }
        }

        const recoveryPct = Number((((maxRecoveryClose - troughClose) / troughClose) * 100).toFixed(2));

        let bucket: HistoricalCorrectionEpisode['depthBucket'] = '-5% to -10%';
        if (depthPct < -30) bucket = '< -30%';
        else if (depthPct < -20) bucket = '-20% to -30%';
        else if (depthPct < -15) bucket = '-15% to -20%';
        else if (depthPct < -10) bucket = '-10% to -15%';

        episodes.push({
          id: `corr-${episodes.length + 1}-${peakDate}`,
          peakDate,
          peakClose,
          troughDate,
          troughClose,
          drawdownPct: depthPct,
          depthBucket: bucket,
          recoveryPeakClose: maxRecoveryClose,
          recoveryPeakDate: maxRecoveryDate,
          recoveryPct,
          sessionsToPeak: Math.max(1, sessionsToPeak),
          reachedThreshold5: recoveryPct >= 5,
          reachedThreshold10: recoveryPct >= 10,
          reachedThreshold15: recoveryPct >= 15,
          reachedThreshold20: recoveryPct >= 20,
        });

        // Reset tracking for next cycle: reinitialize peak and trough cleanly
        peakClose = currentClose;
        peakDate = candles[i].date;
        peakIdx = i;
        troughClose = currentClose;
        troughDate = candles[i].date;
        troughIdx = i;
        inDrawdown = false;
      }
    }
  }

  // Group into standard buckets
  const bucketOrder: HistoricalCorrectionEpisode['depthBucket'][] = [
    '-5% to -10%',
    '-10% to -15%',
    '-15% to -20%',
    '-20% to -30%',
    '< -30%',
  ];

  const bucketSummaries: CorrectionBucketSummary[] = bucketOrder.map((bName) => {
    const matched = episodes.filter((e) => e.depthBucket === bName);
    if (matched.length === 0) {
      return {
        bucket: bName,
        episodeCount: 0,
        avgDrawdownPct: 0,
        avgReboundPct: 0,
        medianReboundPct: 0,
        avgSessionsToPeak: 0,
        winRate10Pct: 0,
        winRate20Pct: 0,
      };
    }

    const avgDd = Number((matched.reduce((acc, e) => acc + e.drawdownPct, 0) / matched.length).toFixed(2));
    const avgReb = Number((matched.reduce((acc, e) => acc + e.recoveryPct, 0) / matched.length).toFixed(2));
    const sortedRebounds = [...matched].map((m) => m.recoveryPct).sort((a, b) => a - b);
    const medianReb = sortedRebounds[Math.floor(sortedRebounds.length / 2)] ?? 0;
    const avgSessions = Math.round(matched.reduce((acc, e) => acc + e.sessionsToPeak, 0) / matched.length);
    const win10 = Number(((matched.filter((e) => e.reachedThreshold10).length / matched.length) * 100).toFixed(1));
    const win20 = Number(((matched.filter((e) => e.reachedThreshold20).length / matched.length) * 100).toFixed(1));

    return {
      bucket: bName,
      episodeCount: matched.length,
      avgDrawdownPct: avgDd,
      avgReboundPct: avgReb,
      medianReboundPct: medianReb,
      avgSessionsToPeak: avgSessions,
      winRate10Pct: win10,
      winRate20Pct: win20,
    };
  });

  // --- B. Initial Rebound After Deep Drawdown (Peak -> DD >= 30% -> Trough -> First Rebound Peak -> Subsequent >= 10% Decline) ---
  const deepDrawdowns: DeepDrawdownEpisode[] = [];
  for (let i = 0; i < candles.length - 100; i++) {
    const pClose = candles[i].close;
    let minClose = pClose;
    let minIdx = i;

    // Search for a >= 30% drop within next 250 sessions
    for (let j = i + 1; j < Math.min(candles.length, i + 250); j++) {
      if (candles[j].close < minClose) {
        minClose = candles[j].close;
        minIdx = j;
      }
    }

    const dd = ((minClose - pClose) / pClose) * 100;
    if (dd <= -30.0) {
      // Confirmed deep drawdown >= 30%
      // Now track First Rebound Peak that experiences a subsequent >= 10% decline
      let firstPeakClose = minClose;
      let firstPeakIdx = minIdx;
      let confirmed = false;
      let subDeclinePct = 0;
      let subDeclineTroughDate = '';
      let subDeclineTroughClose = 0;

      for (let k = minIdx + 1; k < Math.min(candles.length, minIdx + 160); k++) {
        if (candles[k].close > firstPeakClose) {
          firstPeakClose = candles[k].close;
          firstPeakIdx = k;
        }

        // Test if a >= 10% pullback happened from this first peak
        const dropFromPeak = ((candles[k].close - firstPeakClose) / firstPeakClose) * 100;
        if (dropFromPeak <= -10.0 && firstPeakClose > minClose * 1.1) {
          confirmed = true;
          subDeclinePct = Number(dropFromPeak.toFixed(2));
          subDeclineTroughDate = candles[k].date;
          subDeclineTroughClose = candles[k].close;
          break;
        }
      }

      if (confirmed) {
        const rebPct = Number((((firstPeakClose - minClose) / minClose) * 100).toFixed(2));
        deepDrawdowns.push({
          id: `deep-${deepDrawdowns.length + 1}-${candles[i].date}`,
          peakDate: candles[i].date,
          peakClose: pClose,
          drawdownPct: Number(dd.toFixed(2)),
          troughDate: candles[minIdx].date,
          troughClose: minClose,
          firstReboundPeakDate: candles[firstPeakIdx].date,
          firstReboundPeakClose: firstPeakClose,
          reboundPct: rebPct,
          reboundDurationSessions: firstPeakIdx - minIdx,
          subsequentDeclinePct: subDeclinePct,
          subsequentDeclineTroughDate: subDeclineTroughDate,
          subsequentDeclineTroughClose: subDeclineTroughClose,
        });

        // Fast-forward index to avoid overlapping detection
        i = minIdx + 120;
      }
    }
  }

  return {
    episodes,
    bucketSummaries,
    deepDrawdowns,
  };
}

// ===========================================================================
// Engine 3: RSI Oversold & Near-Oversold Rebound Analysis
// ===========================================================================
export function computeRsiAnalysis(
  indexKey: string,
  period: IntelligencePeriod = 'MAX'
): {
  zoneAEvents: RsiZoneAEvent[];
  zoneAStats: RsiZoneStats;
  zoneBEvents: RsiZoneBEvent[];
  zoneBStats: RsiZoneStats;
} {
  const allCandles = getDailyCandlesForIndex(indexKey);
  const { candles } = sliceCandlesByPeriod(allCandles, period);

  const zoneAEvents: RsiZoneAEvent[] = [];
  const zoneBEvents: RsiZoneBEvent[] = [];

  let inZoneA = false;
  let zoneAMinRsi = 100;
  let zoneAMinIdx = -1;

  let inZoneB = false;
  let zoneBMinRsi = 100;
  let zoneBMinIdx = -1;

  for (let i = 15; i < candles.length - 63; i++) {
    const rsi = candles[i].rsi14;
    if (rsi === undefined) continue;

    // --- Zone A: RSI <= 30 ---
    if (rsi <= 30.0) {
      inZoneA = true;
      if (rsi < zoneAMinRsi) {
        zoneAMinRsi = rsi;
        zoneAMinIdx = i;
      }
    } else if (inZoneA && rsi > 32.0) {
      // Completed Zone A cycle
      if (zoneAMinIdx >= 0) {
        const oversoldCandle = candles[zoneAMinIdx];
        const p0 = oversoldCandle.close;

        const p5 = candles[zoneAMinIdx + 5]?.close ?? p0;
        const p10 = candles[zoneAMinIdx + 10]?.close ?? p0;
        const p21 = candles[zoneAMinIdx + 21]?.close ?? p0;
        const p63 = candles[zoneAMinIdx + 63]?.close ?? p0;
        const p120 = candles[zoneAMinIdx + 120]?.close ?? candles[candles.length - 1]?.close ?? p0;
        const p180 = candles[zoneAMinIdx + 180]?.close ?? candles[candles.length - 1]?.close ?? p0;

        let max63 = p0;
        let recoveryDate: string | undefined = undefined;
        let sessionsToRec: number | undefined = undefined;

        for (let f = 1; f <= 63; f++) {
          const forwardCandle = candles[zoneAMinIdx + f];
          if (!forwardCandle) break;
          if (forwardCandle.close > max63) max63 = forwardCandle.close;
          if (forwardCandle.rsi14 !== undefined && forwardCandle.rsi14 >= 50.0 && !recoveryDate) {
            recoveryDate = forwardCandle.date;
            sessionsToRec = f;
          }
        }

        zoneAEvents.push({
          id: `rsi-a-${zoneAEvents.length + 1}-${oversoldCandle.date}`,
          oversoldDate: oversoldCandle.date,
          oversoldPrice: p0,
          minRsi: zoneAMinRsi,
          return5d: Number((((p5 - p0) / p0) * 100).toFixed(2)),
          return10d: Number((((p10 - p0) / p0) * 100).toFixed(2)),
          return21d: Number((((p21 - p0) / p0) * 100).toFixed(2)),
          return63d: Number((((p63 - p0) / p0) * 100).toFixed(2)),
          return120d: Number((((p120 - p0) / p0) * 100).toFixed(2)),
          return180d: Number((((p180 - p0) / p0) * 100).toFixed(2)),
          maxRebound63d: Number((((max63 - p0) / p0) * 100).toFixed(2)),
          recoveryDateAbove50: recoveryDate,
          sessionsToRecoveryAbove50: sessionsToRec,
        });
      }

      inZoneA = false;
      zoneAMinRsi = 100;
      zoneAMinIdx = -1;
    }

    // --- Zone B: Pure Near-Oversold (30 < RSI <= 35) ---
    // Only triggers if price did not breach <= 30 in the surrounding cluster
    if (rsi > 30.0 && rsi <= 35.0 && !inZoneA) {
      inZoneB = true;
      if (rsi < zoneBMinRsi) {
        zoneBMinRsi = rsi;
        zoneBMinIdx = i;
      }
    } else if (inZoneB && (rsi > 37.0 || rsi <= 30.0)) {
      if (zoneBMinIdx >= 0 && rsi > 30.0) {
        const eventCandle = candles[zoneBMinIdx];
        const p0 = eventCandle.close;
        const p21 = candles[zoneBMinIdx + 21]?.close ?? p0;

        let max21 = p0;
        let peakIdx = 0;
        for (let f = 1; f <= 21; f++) {
          const fc = candles[zoneBMinIdx + f];
          if (!fc) break;
          if (fc.close > max21) {
            max21 = fc.close;
            peakIdx = f;
          }
        }

        const maxReb21 = Number((((max21 - p0) / p0) * 100).toFixed(2));
        const ret21 = Number((((p21 - p0) / p0) * 100).toFixed(2));

        zoneBEvents.push({
          id: `rsi-b-${zoneBEvents.length + 1}-${eventCandle.date}`,
          eventDate: eventCandle.date,
          price: p0,
          rsi: zoneBMinRsi,
          return21d: ret21,
          maxRebound21d: maxReb21,
          reached8Pct: maxReb21 >= 8.0,
          sessionsToPeak21d: Math.max(1, peakIdx),
        });
      }

      inZoneB = false;
      zoneBMinRsi = 100;
      zoneBMinIdx = -1;
    }
  }

  // Summaries
  const calcStats = (events: any[], isB: boolean = false): RsiZoneStats => {
    if (events.length === 0) {
      return { sampleSize: 0, avgReturn21d: 0, medianReturn21d: 0, winRate21d: 0, avgMaxRebound: 0 };
    }
    const avg21 = Number((events.reduce((a, b) => a + b.return21d, 0) / events.length).toFixed(2));
    const sorted21 = [...events].map((e) => e.return21d).sort((a, b) => a - b);
    const median21 = sorted21[Math.floor(sorted21.length / 2)] ?? 0;
    const winRate21 = Number(((events.filter((e) => e.return21d > 0).length / events.length) * 100).toFixed(1));

    if (!isB) {
      const avg5 = Number((events.reduce((a, b) => a + (b.return5d ?? 0), 0) / events.length).toFixed(2));
      const avg10 = Number((events.reduce((a, b) => a + b.return10d, 0) / events.length).toFixed(2));
      const avg63 = Number((events.reduce((a, b) => a + b.return63d, 0) / events.length).toFixed(2));
      const avg120 = Number((events.reduce((a, b) => a + (b.return120d ?? 0), 0) / events.length).toFixed(2));
      const avg180 = Number((events.reduce((a, b) => a + (b.return180d ?? 0), 0) / events.length).toFixed(2));
      const avgMax = Number((events.reduce((a, b) => a + b.maxRebound63d, 0) / events.length).toFixed(2));
      const minRsi = Math.min(...events.map((e) => e.minRsi));
      return {
        sampleSize: events.length,
        avgReturn5d: avg5,
        avgReturn10d: avg10,
        avgReturn21d: avg21,
        avgReturn63d: avg63,
        avgReturn120d: avg120,
        avgReturn180d: avg180,
        medianReturn21d: median21,
        winRate21d: winRate21,
        avgMaxRebound: avgMax,
        minRsiObserved: minRsi,
      };
    } else {
      const hitRate8 = Number(((events.filter((e) => e.reached8Pct).length / events.length) * 100).toFixed(1));
      const avgMax = Number((events.reduce((a, b) => a + b.maxRebound21d, 0) / events.length).toFixed(2));
      return {
        sampleSize: events.length,
        avgReturn21d: avg21,
        medianReturn21d: median21,
        winRate21d: winRate21,
        hitRate8Pct: hitRate8,
        avgMaxRebound: avgMax,
      };
    }
  };

  return {
    zoneAEvents,
    zoneAStats: calcStats(zoneAEvents, false),
    zoneBEvents,
    zoneBStats: calcStats(zoneBEvents, true),
  };
}

