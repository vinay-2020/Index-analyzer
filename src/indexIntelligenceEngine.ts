// Seeded pseudorandom generator for deterministic, repeatable daily fluctuations
function pseudoRandom(seed: number): number {
  const x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

// Generate full chronological daily series from Jan 2011 to Sep 2026
export function getDailyCandlesForIndex(indexKey: string): DailyCandle[] {
  if (DAILY_SERIES_CACHE.has(indexKey)) {
    return DAILY_SERIES_CACHE.get(indexKey)!;
  }

  const meta = HMIE_INDEX_UNIVERSE.find((u) => u.key === indexKey) || HMIE_INDEX_UNIVERSE[0];
  const targetClose = meta.currentClose;

  // Derive idiosyncratic beta and volatility factor
  let beta = 1.0;
  let volFactor = 1.0;
  if (meta.category === 'Sector') {
    beta = indexKey.includes('BANK') || indexKey.includes('METAL') || indexKey.includes('REALTY') ? 1.35 : 0.9;
    volFactor = 1.25;
  } else if (meta.category === 'Factor') {
    beta = indexKey.includes('ALPHA') || indexKey.includes('MOMENTUM') ? 1.4 : 0.85;
    volFactor = 1.3;
  } else if (indexKey.includes('SMLCAP') || indexKey.includes('MICROCAP')) {
    beta = 1.45;
    volFactor = 1.4;
  } else if (indexKey.includes('MIDCAP')) {
    beta = 1.25;
    volFactor = 1.2;
  }

  // Generate trading day calendar
  const startYear = 2011;
  const endYear = 2026;
  const rawDates: string[] = [];

  for (let y = startYear; y <= endYear; y++) {
    const maxMonth = y === 2026 ? 9 : 12;
    for (let m = 1; m <= maxMonth; m++) {
      const maxDays = m === 2 ? 28 : (m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31);
      const daysInMonth = y === 2026 && m === 9 ? 18 : maxDays;
      for (let d = 1; d <= daysInMonth; d++) {
        const dt = new Date(y, m - 1, d);
        const dayOfWeek = dt.getDay();
        // Monday to Friday
        if (dayOfWeek >= 1 && dayOfWeek <= 5) {
          rawDates.push(`${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`);
        }
      }
    }
  }

  // Pre-calculate cumulative daily growth
  const totalDays = rawDates.length;
  const dailyMultipliers: number[] = new Array(totalDays);
  let seed = indexKey.split('').reduce((acc, char) => acc + char.charCodeAt(0), 100);

  for (let i = 0; i < totalDays; i++) {
    const dateStr = rawDates[i];
    const y = parseInt(dateStr.slice(0, 4));
    const m = parseInt(dateStr.slice(5, 7));
    const monthlyBenchReturn = (BENCHMARK_MONTHLY_RETURNS[y]?.[m] ?? 0.5) * beta;
    const dailyDrift = (monthlyBenchReturn / 21) / 100;
    
    seed = (seed * 9301 + 49297) % 233280;
    const rand = (pseudoRandom(seed) - 0.495) * 0.022 * volFactor;
    dailyMultipliers[i] = 1 + dailyDrift + rand;
  }

  // Work backwards from current target close
  const closes: number[] = new Array(totalDays);
  closes[totalDays - 1] = targetClose;
  for (let i = totalDays - 2; i >= 0; i--) {
    closes[i] = closes[i + 1] / dailyMultipliers[i + 1];
  }

  // Build daily candles
  const candles: DailyCandle[] = new Array(totalDays);
  for (let i = 0; i < totalDays; i++) {
    const c = Number(closes[i].toFixed(2));
    const prevC = i > 0 ? closes[i - 1] : c * 0.998;
    const changePct = Number((((c - prevC) / prevC) * 100).toFixed(2));
    const spread = Math.abs(c * 0.008 * volFactor);
    const o = Number((prevC + (c - prevC) * 0.3).toFixed(2));
    const h = Number((Math.max(o, c) + spread * 0.6).toFixed(2));
    const l = Number((Math.min(o, c) - spread * 0.6).toFixed(2));
    const volume = Math.round(500000 + pseudoRandom(i) * 1500000);

    candles[i] = {
      date: rawDates[i],
      open: o,
      high: h,
      low: l,
      close: c,
      volume,
      changePct,
    };
  }

  // Compute EMAs
  computeEmaInPlace(candles, 20, 'ema20');
  computeEmaInPlace(candles, 50, 'ema50');
  computeEmaInPlace(candles, 100, 'ema100');
  computeEmaInPlace(candles, 200, 'ema200');
  computeEmaInPlace(candles, 400, 'ema400');
  computeEmaInPlace(candles, 500, 'ema500');

  // Compute 14-period RSI
  computeRsiInPlace(candles, 14);

  DAILY_SERIES_CACHE.set(indexKey, candles);
  return candles;
}

function computeEmaInPlace(candles: DailyCandle[], period: number, key: 'ema20' | 'ema50' | 'ema100' | 'ema200' | 'ema400' | 'ema500') {
  const k = 2 / (period + 1);
  if (candles.length < period) return;

  // Initialize with SMA
  let sum = 0;
  for (let i = 0; i < period; i++) {
    sum += candles[i].close;
  }
  let prevEma = sum / period;
  candles[period - 1][key] = Number(prevEma.toFixed(2));

  for (let i = period; i < candles.length; i++) {
    const ema = candles[i].close * k + prevEma * (1 - k);
    candles[i][key] = Number(ema.toFixed(2));
    prevEma = ema;
  }
}

function computeRsiInPlace(candles: DailyCandle[], period: number = 14) {
  if (candles.length <= period) return;

  let gainSum = 0;
  let lossSum = 0;

  for (let i = 1; i <= period; i++) {
    const diff = candles[i].close - candles[i - 1].close;
    if (diff >= 0) gainSum += diff;
    else lossSum += Math.abs(diff);
  }

  let avgGain = gainSum / period;
  let avgLoss = lossSum / period;

  let rs = avgLoss === 0 ? 100 : avgGain / avgLoss;
  candles[period].rsi14 = Number((100 - (100 / (1 + rs))).toFixed(1));

  for (let i = period + 1; i < candles.length; i++) {
    const diff = candles[i].close - candles[i - 1].close;
    const currentGain = diff >= 0 ? diff : 0;
    const currentLoss = diff < 0 ? Math.abs(diff) : 0;

    avgGain = (avgGain * (period - 1) + currentGain) / period;
    avgLoss = (avgLoss * (period - 1) + currentLoss) / period;

    rs = avgLoss === 0 ? 100 : avgGain / avgLoss;
    candles[i].rsi14 = Number((100 - (100 / (1 + rs))).toFixed(1));
  }
}

// Slice candles by period (MAX, 15Y, 10Y, 5Y, 3Y)
export function sliceCandlesByPeriod(candles: DailyCandle[], period: IntelligencePeriod): { candles: DailyCandle[]; isSufficient: boolean; years: number } {
  if (!candles || candles.length === 0) {
    return { candles: [], isSufficient: false, years: 0 };
  }

  const lastDate = new Date(candles[candles.length - 1].date);
  let targetYears = 15;
  if (period === 'MAX') targetYears = 30;
  else if (period === '15Y') targetYears = 15;
  else if (period === '10Y') targetYears = 10;
  else if (period === '5Y') targetYears = 5;
  else if (period === '3Y') targetYears = 3;

  const cutoff = new Date(lastDate);
  cutoff.setFullYear(cutoff.getFullYear() - targetYears);
  const cutoffStr = cutoff.toISOString().slice(0, 10);

  const filtered = candles.filter((c) => c.date >= cutoffStr);
  const totalDays = filtered.length;
  const years = Number((totalDays / 250).toFixed(1));

  // Determine sufficiency: period requires at least 85% of trading days
  const requiredDays = period === 'MAX' ? 250 : targetYears * 210;
  const isSufficient = filtered.length >= requiredDays;

  return {
    candles: filtered,
    isSufficient,
    years: Math.max(1, years),
  };
}

