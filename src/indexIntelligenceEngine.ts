// Engine 4: Long-Term EMA Support Behaviour (EMA20 - EMA500, ±3% Zone)
// ===========================================================================
export function computeEmaSupportAnalysis(
  indexKey: string,
  period: IntelligencePeriod = 'MAX'
): {
  summaryRows: EmaSummaryRow[];
  episodesByEma: Record<EmaType, EmaInteractionEpisode[]>;
} {
  const allCandles = getDailyCandlesForIndex(indexKey);
  const { candles } = sliceCandlesByPeriod(allCandles, period);

  const emaConfigs: { type: EmaType; prop: 'ema20' | 'ema50' | 'ema100' | 'ema200' | 'ema400' | 'ema500'; period: number }[] = [
    { type: 'EMA20', prop: 'ema20', period: 20 },
    { type: 'EMA50', prop: 'ema50', period: 50 },
    { type: 'EMA100', prop: 'ema100', period: 100 },
    { type: 'EMA200', prop: 'ema200', period: 200 },
    { type: 'EMA400', prop: 'ema400', period: 400 },
    { type: 'EMA500', prop: 'ema500', period: 500 },
  ];

  const episodesByEma: Record<EmaType, EmaInteractionEpisode[]> = {
    EMA20: [],
    EMA50: [],
    EMA100: [],
    EMA200: [],
    EMA400: [],
    EMA500: [],
  };

  const summaryRows: EmaSummaryRow[] = [];

  for (const cfg of emaConfigs) {
    const list: EmaInteractionEpisode[] = [];
    const minStartIdx = Math.max(cfg.period + 10, 50);

    for (let i = minStartIdx; i < candles.length - 40; i++) {
      const emaVal = candles[i][cfg.prop];
      if (!emaVal || emaVal <= 0) continue;

      const distPct = ((candles[i].close - emaVal) / emaVal) * 100;

      // Within +/- 3.0% zone
      if (Math.abs(distPct) <= 3.0) {
        // Record touch
        const touchClose = candles[i].close;
        const p20 = candles[i + 20]?.close ?? touchClose;
        const p40 = candles[i + 40]?.close ?? touchClose;

        let maxHigh = touchClose;
        let minLow = touchClose;

        for (let f = 1; f <= 40; f++) {
          const fc = candles[i + f];
          if (!fc) break;
          if (fc.high > maxHigh) maxHigh = fc.high;
          if (fc.low < minLow) minLow = fc.low;
        }

        const mfe = Number((((maxHigh - touchClose) / touchClose) * 100).toFixed(2));
        const mae = Number((((minLow - touchClose) / touchClose) * 100).toFixed(2));
        const r20 = Number((((p20 - touchClose) / touchClose) * 100).toFixed(2));
        const r40 = Number((((p40 - touchClose) / touchClose) * 100).toFixed(2));

        let classification: EmaInteractionEpisode['classification'] = 'NEUTRAL_CONSOLIDATION';
        if (mfe >= 3.0 && mae > -3.0) {
          classification = 'SUPPORT_CONFIRMED';
        } else if (mae <= -3.0) {
          classification = 'BREAKDOWN';
        }

        list.push({
          id: `ema-${cfg.type}-${list.length + 1}-${candles[i].date}`,
          date: candles[i].date,
          close: touchClose,
          emaValue: emaVal,
          distancePct: Number(distPct.toFixed(2)),
          maxFavorableExcursion40d: mfe,
          maxAdverseExcursion40d: mae,
          return20d: r20,
          return40d: r40,
          classification,
        });

        // Fast-forward at least 15 sessions to prevent grouping continuous touches
        i += 15;
      }
    }

    episodesByEma[cfg.type] = list;

    // Current distance
    const latestCandle = candles[candles.length - 1];
    const latestEma = latestCandle ? latestCandle[cfg.prop] ?? latestCandle.close : 0;
    const currentDist = latestCandle && latestEma > 0 ? Number((((latestCandle.close - latestEma) / latestEma) * 100).toFixed(2)) : 0;

    const total = list.length;
    const suppCount = list.filter((l) => l.classification === 'SUPPORT_CONFIRMED').length;
    const brkCount = list.filter((l) => l.classification === 'BREAKDOWN').length;

    summaryRows.push({
      emaType: cfg.type,
      period: cfg.period,
      totalInteractions: total,
      supportConfirmedCount: suppCount,
      supportRatePct: total > 0 ? Number(((suppCount / total) * 100).toFixed(1)) : 0,
      breakdownCount: brkCount,
      breakdownRatePct: total > 0 ? Number(((brkCount / total) * 100).toFixed(1)) : 0,
      avgDistanceAtTouchPct: total > 0 ? Number((list.reduce((a, b) => a + b.distancePct, 0) / total).toFixed(2)) : 0,
      avgMaxRebound40d: total > 0 ? Number((list.reduce((a, b) => a + b.maxFavorableExcursion40d, 0) / total).toFixed(2)) : 0,
      avgMaxDrawdown40d: total > 0 ? Number((list.reduce((a, b) => a + b.maxAdverseExcursion40d, 0) / total).toFixed(2)) : 0,
      avgReturn20d: total > 0 ? Number((list.reduce((a, b) => a + b.return20d, 0) / total).toFixed(2)) : 0,
      avgReturn40d: total > 0 ? Number((list.reduce((a, b) => a + b.return40d, 0) / total).toFixed(2)) : 0,
      currentDistancePct: currentDist,
    });
  }

  return {
    summaryRows,
    episodesByEma,
  };
}

// ===========================================================================
// Engine 5: Seasonality & Fiscal-Year Regime Transition (March -> April)
// ===========================================================================
export function computeSeasonalityAndFiscalCycles(
  indexKey: string,
  period: IntelligencePeriod = 'MAX'
): {
  quarterlyStats: QuarterlyStatsItem[];
  fiscalTransitionStats: FiscalYearTransitionStats;
} {
  const allCandles = getDailyCandlesForIndex(indexKey);
  const { candles } = sliceCandlesByPeriod(allCandles, period);

  // Group by year and month to get exact month-end closes
  const monthEndCloses = new Map<string, { year: number; month: number; close: number }>();
  for (const c of candles) {
    const yr = parseInt(c.date.slice(0, 4));
    const mo = parseInt(c.date.slice(5, 7));
    const key = `${yr}-${mo}`;
    monthEndCloses.set(key, { year: yr, month: mo, close: c.close });
  }

  // Derive monthly returns
  const sortedKeys = Array.from(monthEndCloses.keys()).sort();
  const monthlyReturns = new Map<string, number>();

  for (let i = 1; i < sortedKeys.length; i++) {
    const prev = monthEndCloses.get(sortedKeys[i - 1])!;
    const curr = monthEndCloses.get(sortedKeys[i])!;
    if (prev.close > 0) {
      const ret = ((curr.close - prev.close) / prev.close) * 100;
      monthlyReturns.set(`${curr.year}-${curr.month}`, Number(ret.toFixed(2)));
    }
  }

  // --- A. Quarterly Statistics (Q1: Jan-Mar, Q2: Apr-Jun, Q3: Jul-Sep, Q4: Oct-Dec) ---
  const quarterReturns: Record<number, number[]> = { 1: [], 2: [], 3: [], 4: [] };
  const startYr = parseInt(sortedKeys[0]?.split('-')[0] || '2011');
  const endYr = parseInt(sortedKeys[sortedKeys.length - 1]?.split('-')[0] || '2026');

  for (let y = startYr; y <= endYr; y++) {
    for (let q = 1; q <= 4; q++) {
      if (y === 2026 && q > 3) continue;
      const mStart = (q - 1) * 3 + 1;
      const m1 = monthlyReturns.get(`${y}-${mStart}`) ?? 0;
      const m2 = monthlyReturns.get(`${y}-${mStart + 1}`) ?? 0;
      const m3 = monthlyReturns.get(`${y}-${mStart + 2}`) ?? 0;

      // Compound 3 months: (1 + m1)*(1 + m2)*(1 + m3) - 1
      const qRet = Number((((1 + m1 / 100) * (1 + m2 / 100) * (1 + m3 / 100) - 1) * 100).toFixed(2));
      quarterReturns[q].push(qRet);
    }
  }

  const qNames = ['Q1', 'Q2', 'Q3', 'Q4'];
  const qPeriods = ['Jan–Mar', 'Apr–Jun', 'Jul–Sep', 'Oct–Dec'];

  const quarterlyStats: QuarterlyStatsItem[] = [1, 2, 3, 4].map((q) => {
    const rets = quarterReturns[q];
    if (rets.length === 0) {
      return {
        quarter: q,
        quarterName: qNames[q - 1],
        calendarPeriod: qPeriods[q - 1],
        sampleSize: 0,
        avgReturnPct: 0,
        medianReturnPct: 0,
        winRatePct: 0,
        loseRatePct: 0,
        maxReturnPct: 0,
        minReturnPct: 0,
        stdDevPct: 0,
      };
    }

    const avg = Number((rets.reduce((a, b) => a + b, 0) / rets.length).toFixed(2));
    const sorted = [...rets].sort((a, b) => a - b);
    const med = sorted[Math.floor(sorted.length / 2)] ?? 0;
    const wins = rets.filter((r) => r > 0).length;
    const winRate = Number(((wins / rets.length) * 100).toFixed(1));
    const loseRate = Number((100 - winRate).toFixed(1));
    const maxR = Math.max(...rets);
    const minR = Math.min(...rets);

    let sumSq = 0;
    for (const r of rets) sumSq += Math.pow(r - avg, 2);
    const sd = Number(Math.sqrt(sumSq / Math.max(1, rets.length - 1)).toFixed(2));

    return {
      quarter: q,
      quarterName: qNames[q - 1],
      calendarPeriod: qPeriods[q - 1],
      sampleSize: rets.length,
      avgReturnPct: avg,
      medianReturnPct: med,
      winRatePct: winRate,
      loseRatePct: loseRate,
      maxReturnPct: maxR,
      minReturnPct: minR,
      stdDevPct: sd,
    };
  });

  // --- B. Fiscal Year Regime Transition: March -> April ---
  const fiscalObs: FiscalYearTransitionObservation[] = [];

  for (let y = startYr; y <= endYr; y++) {
    const marRet = monthlyReturns.get(`${y}-3`);
    const aprRet = monthlyReturns.get(`${y}-4`);

    if (marRet !== undefined && aprRet !== undefined) {
      const delta = Number((aprRet - marRet).toFixed(2));
      const comp = Number((((1 + marRet / 100) * (1 + aprRet / 100) - 1) * 100).toFixed(2));

      let dir: FiscalYearTransitionObservation['direction'] = 'EXPANSION';
      if (marRet < 0 && aprRet > 0) dir = 'REVERSAL_TO_GREEN';
      else if (marRet > 0 && aprRet > 0) dir = 'CONTINUATION_GREEN';
      else if (aprRet < marRet) dir = 'CONTRACTION';

      fiscalObs.push({
        year: y,
        marchReturnPct: marRet,
        aprilReturnPct: aprRet,
        transitionDeltaPct: delta,
        compoundedTwoMonthPct: comp,
        direction: dir,
      });
    }
  }

  // Calculate summary stats
  const totalObs = fiscalObs.length;
  const avgMar = totalObs > 0 ? Number((fiscalObs.reduce((a, b) => a + b.marchReturnPct, 0) / totalObs).toFixed(2)) : 0;
  const avgApr = totalObs > 0 ? Number((fiscalObs.reduce((a, b) => a + b.aprilReturnPct, 0) / totalObs).toFixed(2)) : 0;
  const avgDelta = Number((avgApr - avgMar).toFixed(2));
  const avgComp = totalObs > 0 ? Number((fiscalObs.reduce((a, b) => a + b.compoundedTwoMonthPct, 0) / totalObs).toFixed(2)) : 0;

  const aprWins = fiscalObs.filter((o) => o.aprilReturnPct > 0).length;
  const aprWinRate = totalObs > 0 ? Number(((aprWins / totalObs) * 100).toFixed(1)) : 0;

  const aprBeatMar = fiscalObs.filter((o) => o.aprilReturnPct > o.marchReturnPct).length;
  const aprBeatMarPct = totalObs > 0 ? Number(((aprBeatMar / totalObs) * 100).toFixed(1)) : 0;

  const negMar = fiscalObs.filter((o) => o.marchReturnPct < 0);
  const posAprAfterNegMar = negMar.filter((o) => o.aprilReturnPct > 0).length;
  const posAprAfterNegMarPct = negMar.length > 0 ? Number(((posAprAfterNegMar / negMar.length) * 100).toFixed(1)) : 0;

  let bestYear = { year: 2011, deltaPct: -999, aprilReturn: 0 };
  let worstYear = { year: 2011, deltaPct: 999, aprilReturn: 0 };

  for (const o of fiscalObs) {
    if (o.transitionDeltaPct > bestYear.deltaPct) {
      bestYear = { year: o.year, deltaPct: o.transitionDeltaPct, aprilReturn: o.aprilReturnPct };
    }
    if (o.transitionDeltaPct < worstYear.deltaPct) {
      worstYear = { year: o.year, deltaPct: o.transitionDeltaPct, aprilReturn: o.aprilReturnPct };
    }
  }

  const fiscalTransitionStats: FiscalYearTransitionStats = {
    sampleSize: totalObs,
    avgMarchReturnPct: avgMar,
    avgAprilReturnPct: avgApr,
    avgTransitionDeltaPct: avgDelta,
    avgCompoundedTwoMonthPct: avgComp,
    aprilWinRatePct: aprWinRate,
    aprilOutperformedMarchPct: aprBeatMarPct,
    positiveAprilAfterNegativeMarchPct: posAprAfterNegMarPct,
    bestTransitionYear: bestYear,
    worstTransitionYear: worstYear,
    observations: fiscalObs,
  };

  return {
    quarterlyStats,
    fiscalTransitionStats,
  };
}

// ===========================================================================
// Top Research Summary Metric Aggregator
// ===========================================================================
export function getTopIntelligenceSummary(
  indexKey: string,
  period: IntelligencePeriod = '15Y'
): IndexIntelligenceSummary {
  const meta = HMIE_INDEX_UNIVERSE.find((u) => u.key === indexKey) || HMIE_INDEX_UNIVERSE[0];
  const bench = computeBenchmarkComparison(indexKey, period);
  const rsi = computeRsiAnalysis(indexKey, period);
  const ema = computeEmaSupportAnalysis(indexKey, period);
  const seasonality = computeSeasonalityAndFiscalCycles(indexKey, period);

  const ema200Row = ema.summaryRows.find((r) => r.emaType === 'EMA200') || ema.summaryRows[3];

  let bestQ = { name: 'Q1', avgReturn: -999 };
  let worstQ = { name: 'Q1', avgReturn: 999 };
  for (const q of seasonality.quarterlyStats) {
    if (q.avgReturnPct > bestQ.avgReturn) bestQ = { name: q.quarterName, avgReturn: q.avgReturnPct };
    if (q.avgReturnPct < worstQ.avgReturn) worstQ = { name: q.quarterName, avgReturn: q.avgReturnPct };
  }

  return {
    indexKey: meta.key,
    name: meta.name,
    symbol: meta.symbol,
    categoryLabel: meta.categoryLabel,
    inceptionDate: meta.inceptionDate,
    parentBenchmarkName: meta.parentBenchmarkName || 'Benchmark mapping unavailable',
    period,
    isHistorySufficient: bench.isHistorySufficient,
    yearsTracked: bench.yearsCovered,
    historicalCagr: bench.target.cagr,
    maxDrawdownPct: bench.target.maxDrawdownPct,
    totalRsiZoneAEvents: rsi.zoneAStats.sampleSize,
    avgReboundAfterOversoldPct: rsi.zoneAStats.avgMaxRebound,
    ema200InteractionsCount: ema200Row?.totalInteractions ?? 0,
    ema200SupportRatePct: ema200Row?.supportRatePct ?? 0,
    bestQuarter: bestQ,
    worstQuarter: worstQ,
  };
}
