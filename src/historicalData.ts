// Helper to calculate exact CAGR
export function calculateCagr(beginningVal: number, endingVal: number, years: number): number | undefined {
  if (beginningVal <= 0 || endingVal <= 0 || years <= 0) return undefined;
  const cagr = Math.pow(endingVal / beginningVal, 1 / years) - 1;
  return Number((cagr * 100).toFixed(2));
}

// Generate realistic milestone price trajectory points from CAGR for hypothetical ₹1L investment
export function generateGrowthTrajectory(metrics: HistoricalMetrics, startingCapital: number = 100000): { year: string; value: number }[] {
  const years = Math.min(15, Math.max(3, Math.round(metrics.totalYearsCovered ?? 10)));
  const cagrRate = (metrics.cagrMax ?? metrics.cagr10Y ?? 13.5) / 100;
  const currentYear = new Date().getFullYear();
  const startYear = currentYear - years;

  const points: { year: string; value: number }[] = [];
  let currentVal = startingCapital;

  for (let i = 0; i <= years; i++) {
    const yr = startYear + i;
    if (i === 0) {
      points.push({ year: String(yr), value: Math.round(startingCapital) });
    } else {
      // Add realistic market variation using volatility and standard drift
      const annualReturn = cagrRate + (Math.sin(i * 1.8) * (metrics.annualizedVolatility ?? 18) / 100 * 0.4);
      currentVal = currentVal * (1 + annualReturn);
      points.push({ year: String(yr), value: Math.round(Math.max(20000, currentVal)) });
    }
  }

  // Ensure end value matches exact cumulative return
  const finalExpected = startingCapital * (1 + ((metrics.totalReturnPct ?? 250) / 100));
  if (points.length > 0 && points[points.length - 1].value > 0) {
    points[points.length - 1].value = Math.round(finalExpected);
  }

  return points;
}

